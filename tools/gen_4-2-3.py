def num(x):
    """Decimal → JSON 숫자 (0.80 → 0.8, 420.0 → 420)"""
    x = D(str(x)).normalize()
    return int(x) if x == x.to_integral() else float(str(x))

def s(x):
    """Decimal → 화면용 문자열 (지수 표기 없이)"""
    x = D(str(x)).normalize()
    return format(x, "f")

def Q(type, text, answer, **kw):
    q = {"type": type, "text": text, "answer": answer}
    q.update(kw)
    return q

def N(text, answer, unit=None, **kw):
    """숫자 답 문항 (소수점 키패드)"""
    if unit: kw["unit"] = unit
    return Q("number", text, num(answer), **kw)

def tx(x, y, t, size=None, anchor=None, color=None):
    st = []
    if size: st.append(f"font-size:{size}px")
    if anchor: st.append(f"text-anchor:{anchor}")
    if color: st.append(f"fill:{color}")
    a = f' style="{";".join(st)}"' if st else ""
    return f'<text x="{x:g}" y="{y:g}"{a}>{t}</text>'

def fig(w, h, *parts):
    return {"w": w, "h": h, "draw": "".join(parts)}

# ---------- 그림: 100칸 모눈 ----------
def grid100(n, x0=10, y0=10, c=15):
    out = []
    for i in range(100):
        r, k = divmod(i, 10)
        fill = FILL if i < n else "#FFFFFF"
        out.append(f'<rect x="{x0 + k * c}" y="{y0 + r * c}" width="{c}" height="{c}" style="fill:{fill};stroke:{GRIDC};stroke-width:1"/>')
    out.append(f'<rect x="{x0}" y="{y0}" width="{10 * c}" height="{10 * c}" style="fill:none;stroke:{INK};stroke-width:2"/>')
    return "".join(out)

def grids(*ns):
    """모눈 여러 개 나란히 (각 170px)"""
    parts = []
    for i, n in enumerate(ns):
        parts.append(grid100(n, x0=10 + i * 190))
    return fig(10 + 190 * len(ns), 170, *parts)

# ---------- 그림: 수직선 ----------
def numline(a, b, arrow, labels=True):
    """a~b를 10칸으로 나눈 수직선, arrow 위치에 화살표"""
    a, b, arrow = D(a), D(b), D(arrow)
    x0, x1, y = 30, 390, 70
    X = lambda v: x0 + float((v - a) / (b - a)) * (x1 - x0)
    parts = [f'<line x1="{x0 - 10}" y1="{y}" x2="{x1 + 10}" y2="{y}"/>']
    for i in range(11):
        xx = x0 + i * (x1 - x0) / 10
        big = i in (0, 10)
        parts.append(f'<line x1="{xx:g}" y1="{y - (12 if big else 7)}" x2="{xx:g}" y2="{y + (12 if big else 7)}" style="stroke-width:{3 if big else 2}"/>')
    if labels:
        parts.append(tx(x0, y + 36, s(a), 18)); parts.append(tx(x1, y + 36, s(b), 18))
    ax = X(arrow)
    parts.append(f'<path d="M {ax - 9:g} {y - 34} L {ax + 9:g} {y - 34} L {ax:g} {y - 16} Z" style="fill:#E0453B;stroke:none"/>')
    parts.append(tx(ax, y - 42, "?", 20, color="#E0453B"))
    return fig(420, 120, *parts)

# ---------- 그림: 세로셈 ----------
def vert(a, b, op, boxes=None):
    """소수점을 맞춘 세로셈. boxes={(행, 칸문자열위치): '㉠'} 대신 a/b 문자열 안의 '□'를 상자로 그림.
    a, b: 문자열(예 '3.7', '□.5'). 마지막 줄은 빈칸."""
    ia, fa = (a.split(".") + [""])[:2]
    ib, fb = (b.split(".") + [""])[:2]
    I, F = max(len(ia), len(ib)), max(len(fa), len(fb))
    cw, x0, y0, rh = 34, 70, 44, 50
    labels = iter("㉠㉡㉢㉣")
    parts = []
    def row(intp, frac, y, show_dot):
        cells = list(" " * (I - len(intp)) + intp) + ["."] + list(frac + " " * (F - len(frac)))
        x = x0
        for ch in cells:
            if ch == ".":
                if show_dot: parts.append(tx(x - 17, y, ".", 30))
                continue
            if ch == "□":
                parts.append(f'<rect x="{x - 14}" y="{y - 30}" width="28" height="36" rx="5" style="fill:#EAF3FD;stroke:#2C7BE0;stroke-width:2.5"/>')
                parts.append(tx(x, y - 3, next(labels), 18, color="#2C7BE0"))
            elif ch != " ":
                parts.append(tx(x, y, ch, 30))
            x += cw
    row(ia, fa, y0, bool(fa))
    row(ib, fb, y0 + rh, bool(fb))
    parts.append(tx(x0 - 40, y0 + rh, op, 30))
    wtot = cw * (I + F)
    parts.append(f'<line x1="{x0 - 50}" y1="{y0 + rh + 16}" x2="{x0 + wtot - 4}" y2="{y0 + rh + 16}"/>')
    return parts, x0, y0 + rh * 2 + 4, wtot

def vfig(a, b, op, result=None):
    parts, x0, y, wtot = vert(a, b, op)
    if result:
        ir, fr = (result.split(".") + [""])[:2]
        ia, fa = (a.split(".") + [""])[:2]; ib, fb = (b.split(".") + [""])[:2]
        I, F = max(len(ia), len(ib), len(ir)), max(len(fa), len(fb), len(fr))
        cells = list(" " * (I - len(ir)) + ir) + ["."] + list(fr)
        x = x0
        for ch in cells:
            if ch == ".": parts.append(tx(x - 17, y, ".", 30)); continue
            if ch == "□":
                parts.append(f'<rect x="{x - 14}" y="{y - 30}" width="28" height="36" rx="5" style="fill:#EAF3FD;stroke:#2C7BE0;stroke-width:2.5"/>')
            elif ch != " ":
                parts.append(tx(x, y, ch, 30))
            x += 34
    else:
        parts.append(f'<rect x="{x0 - 16}" y="{y - 32}" width="{wtot}" height="40" rx="6" style="fill:#EAF3FD;stroke:#2C7BE0;stroke-width:2;stroke-dasharray:6 4"/>')
        parts.append(tx(x0 - 16 + wtot / 2, y - 4, "?", 24, color="#2C7BE0"))
    return fig(max(260, x0 + wtot + 40), 190, *parts)

