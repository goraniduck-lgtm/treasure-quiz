def cmp_q(a, b):
    a, b = D(a), D(b)
    ans = 1 if a > b else 2 if a < b else 3
    return Q("choice", f"두 수의 크기를 비교하여 알맞은 것을 고르세요.\n{s(a)} [ ] {s(b)}", ans,
             options=["＞ (왼쪽이 더 커요)", "＜ (오른쪽이 더 커요)", "＝ (같아요)"])

def pick_q(text, vals, fn, extra=None):
    """vals 중 fn(최대/최소)인 보기를 정답으로"""
    vs = [D(v) for v in vals]
    target = fn(vs)
    return Q("choice", text, vs.index(target) + 1, options=[s(v) if extra is None else extra[i] for i, v in enumerate(vs)])

