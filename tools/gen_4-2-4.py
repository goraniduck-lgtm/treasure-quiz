# ---------------- 그림 도우미 ----------------
def ln(x1, y1, x2, y2, style=""):
    s = f' style="{style}"' if style else ""
    return f'<line x1="{x1:g}" y1="{y1:g}" x2="{x2:g}" y2="{y2:g}"{s}/>'

def dash(x1, y1, x2, y2):
    return ln(x1, y1, x2, y2, "stroke-dasharray:6 5;stroke-width:2")

def poly(*pts, style=""):
    s = f' style="{style}"' if style else ""
    return '<polygon points="' + " ".join(f"{x:g},{y:g}" for x, y in pts) + f'"{s}/>'

def tx(x, y, t, size=None):
    s = f' style="font-size:{size}px"' if size else ""
    return f'<text x="{x:g}" y="{y:g}"{s}>{t}</text>'

def ra(x, y, dx, dy, s=10):
    """축에 나란한 직각 표시. (x,y)=꼭짓점, dx/dy=두 변이 뻗는 방향(±1)"""
    return f'<path d="M {x+dx*s:g} {y:g} L {x+dx*s:g} {y+dy*s:g} L {x:g} {y+dy*s:g}" style="stroke-width:2"/>'

def dot(x, y):
    return f'<circle cx="{x:g}" cy="{y:g}" r="4" style="fill:#1D2A44;stroke:none"/>'

def fig(w, h, *parts, grid=None):
    f = {"w": w, "h": h, "draw": "".join(parts)}
    if grid:
        f["grid"] = grid
    return f

def opt(label=None, figure=None, text=None):
    o = {}
    if label: o["label"] = label
    if figure: o["figure"] = figure
    if text: o["text"] = text
    return o

def vlabels(pts, names, off=16, size=None):
    """다각형 꼭짓점 이름을 중심에서 바깥쪽으로 조금 띄워 쓴다"""
    cx = sum(p[0] for p in pts) / len(pts); cy = sum(p[1] for p in pts) / len(pts)
    out = []
    for (x, y), n in zip(pts, names):
        dx, dy = x - cx, y - cy; d = math.hypot(dx, dy) or 1
        out.append(tx(x + dx / d * off, y + dy / d * off + 6, n, size))
    return "".join(out)

def Q(type, text, answer, **kw):
    q = {"type": type, "text": text, "answer": answer}
    q.update(kw)
    return q

def shapes_row(items, w=640, h=170):
    """여러 도형을 한 그림에: items = [(이름, [점들])]"""
    parts = []
    for name, pts in items:
        parts.append(poly(*pts))
        cx = sum(p[0] for p in pts) / len(pts)
        parts.append(tx(cx, h - 6, name, 24))
    return fig(w, h, *parts, grid=20)

# 자주 쓰는 도형 (옵션 그림용, 160x110 칸)
